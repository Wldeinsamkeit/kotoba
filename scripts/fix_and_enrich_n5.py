def main():
    with open(INPUT, encoding="utf-8") as f:
        data = json.load(f)

    added = 0
    for e in data:
        if not e["meaning"]:
            key = (e["word"], e["reading"])
            if key in LAST_CN:
                e["meaning"] = LAST_CN[key]
                added += 1

    print(f"Added: {added}")

    with_cn = sum(1 for e in data if e["meaning"])
    print(f"With Chinese meaning: {with_cn}/{len(data)}")

    OUTPUT.write_text(
        json.dumps(data, ensure_ascii=False, indent=2),
        encoding="utf-8"
    )

    missing = [e for e in data if not e["meaning"]]
    print(f"Still missing: {len(missing)}")
    for e in missing:
        en = e["meaning_en"][:60] if e["meaning_en"] else "?"
        print(f"  {e['word']}（{e['reading']}）: {en}")


if __name__ == "__main__":
    main()
